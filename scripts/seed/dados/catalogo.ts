const FAZER_LANDER = ["yamaha-fazer-250", "yamaha-lander-250"] as const;

const categoriaPorNome = new Map<string, CategoriaSeed>(CATEGORIAS.map((c) => [c.nome, c]));
const marcaPorNome = new Map<string, MarcaPecaSeed>(MARCAS_PECA.map((m) => [m.nome, m]));

function peca(e: EntradaPeca): ProdutoSeed {
  const categoria = categoriaPorNome.get(e.categoria) as CategoriaSeed;
  const marca = marcaPorNome.get(e.marca) as MarcaPecaSeed;

  let precoVenda = e.preco;
  if (precoVenda === undefined) {
    const sugerido = calcularPrecoSugerido({
      ultimoCusto: e.custo,
      markupProduto: e.markup ?? null,
      markupCategoria: categoria.markupPadrao,
      arredondamento: ARREDONDAMENTO_PRECO_DEMO,
    });
    if (!sugerido) throw new Error(`Sem preço sugerido para ${e.codigo}`);
    precoVenda = paraNumeric(sugerido.preco, "dinheiro") as DecimalTexto;
  }

  const codigosBarras: CodigoBarrasSeed[] = [];
  if (e.ean !== false) {
    const ean = eanFabricante(marca.codigoEan, Number.parseInt(e.codigo, 10));
    codigosBarras.push({ codigo: ean, tipo: "fabricante", fator: "1" });
    if (e.caixa) codigosBarras.push({ codigo: gtin14Embalagem(ean), tipo: "embalagem", fator: e.caixa });
  }

  const custoSaldo = e.saldoSemCusto ? null : e.custo;
  const saldos: ProdutoSeed["saldos"] = {};
  const [simples, real] = e.saldo;
  if (simples !== null) saldos.simples = { quantidade: simples, custoUnitario: custoSaldo };
  if (real !== null) saldos.real = { quantidade: real, custoUnitario: custoSaldo };

  return {
    codigo: e.codigo,
    descricao: e.descricao,
    descricaoCurta: e.curta,
    descricaoCompleta: e.completa ?? null,
    categoria: e.categoria,
    marca: e.marca,
    referenciaFabricante: e.referencia ?? null,
    codigoOriginal: e.original ?? null,
    unidade: e.unidade ?? "UN",
    corredor: e.local[0],
    prateleira: e.local[1],
    gaveta: e.local[2],
    estoqueMinimo: e.minimo,
    markup: e.markup ?? null,
    precoVenda,
    ncm: e.ncm,
    origem: e.origem ?? 0,
    grupoFiscal: e.grupoFiscal ?? categoria.grupoFiscal,
    pesoG: e.pesoG ?? null,
    custo: e.custo,
    codigosBarras,
    aplicacoes: e.aplicacoes ?? [],
    saldos,
  };
}

